"""Google Chat HTTP endpoint for the company AI assistant.

Receives Chat app events for apps that are not Google Workspace add-ons
(MESSAGE, ADDED_TO_SPACE, REMOVED_FROM_SPACE), verifies Google's bearer token,
and routes employee messages through the existing LangGraph workflow.
"""

import asyncio
import logging
from typing import Any

from fastapi import APIRouter, HTTPException, Request, status
from google.auth import exceptions as google_auth_exceptions
from google.auth.transport import requests as google_requests
from google.oauth2 import id_token

from config.settings import settings
from graph import company_assistant, run_agent_graph


logger = logging.getLogger(__name__)

CHAT_ISSUER = "chat@system.gserviceaccount.com"
CHAT_CERTS_URL = "https://www.googleapis.com/service_accounts/v1/metadata/x509/" + CHAT_ISSUER

# Google Chat expects a synchronous reply within 30 seconds; stay under that.
RESPONSE_TIMEOUT_SECONDS = 25
# Google Chat rejects text messages longer than 4096 characters.
MAX_CHAT_TEXT_LENGTH = 4000

WELCOME_TEXT = (
    "Hi! I'm the Company AI Assistant. I can help with company holidays and "
    "working days, HR policies and leave, upcoming company events, employee and "
    "team information, and general company questions. Send me a message to get started."
)
EMPTY_MESSAGE_TEXT = "Please send a question in text so I can help you."
TIMEOUT_TEXT = "Sorry, that took too long to answer. Please try again in a moment."
ERROR_TEXT = "Sorry, I couldn't process your request right now. Please try again later."

router = APIRouter(tags=["google-chat"])


def verify_google_chat_token(authorization: str | None, audience: str) -> bool:
    """Return True only if the bearer token was issued by Google Chat for this app.

    A numeric audience means the project-number JWT flow (checked via `iss`).
    Any other audience means the HTTP endpoint URL ID-token flow (checked via `email`).
    """
    if not authorization or not authorization.startswith("Bearer "):
        return False
    token = authorization[len("Bearer "):].strip()
    request = google_requests.Request()
    try:
        if audience.isdigit():
            claims = id_token.verify_token(
                token, request, audience=audience, certs_url=CHAT_CERTS_URL
            )
            return claims.get("iss") == CHAT_ISSUER
        claims = id_token.verify_oauth2_token(token, request, audience=audience)
        return claims.get("email") == CHAT_ISSUER and claims.get("email_verified") is True
    except (ValueError, google_auth_exceptions.GoogleAuthError):
        return False


def build_thread_id(space_name: str, user_name: str) -> str:
    """Scope LangGraph memory to one employee within one Chat space.

    Keeping the user in the key stops one employee's conversation from leaking
    into another employee's answers in a shared space.
    """
    return f"gchat:{space_name}:{user_name}"


def extract_user_text(message: dict[str, Any]) -> str:
    """Return the message text without the @bot mention (argumentText) when available."""
    return str(message.get("argumentText") or message.get("text") or "").strip()


async def _handle_message(event: dict[str, Any], space_name: str, user_name: str) -> dict[str, Any]:
    query = extract_user_text(event.get("message") or {})
    if not query:
        return {"text": EMPTY_MESSAGE_TEXT}

    thread_id = build_thread_id(space_name, user_name)
    try:
        response_text, agent_key = await asyncio.wait_for(
            run_agent_graph(user_query=query, thread_id=thread_id),
            timeout=RESPONSE_TIMEOUT_SECONDS,
        )
    except asyncio.TimeoutError:
        logger.warning("Google Chat request exceeded %ss.", RESPONSE_TIMEOUT_SECONDS)
        return {"text": TIMEOUT_TEXT}
    except Exception:
        logger.error("Failed to process Google Chat message.", exc_info=True)
        return {"text": ERROR_TEXT}

    logger.info("Google Chat response generated by %s.", agent_key)
    return {"text": response_text[:MAX_CHAT_TEXT_LENGTH]}


async def handle_chat_event(event: dict[str, Any]) -> dict[str, Any]:
    """Map one Chat event to a Chat API message response (empty dict means no reply)."""
    event_type = event.get("eventType") or event.get("type")
    space_name = str((event.get("space") or {}).get("name", ""))
    user_name = str((event.get("user") or {}).get("name", ""))

    if event_type == "ADDED_TO_SPACE":
        logger.info("Google Chat app added to a space.")
        return {"text": WELCOME_TEXT}

    if event_type == "REMOVED_FROM_SPACE":
        company_assistant.checkpointer.delete_thread(build_thread_id(space_name, user_name))
        logger.info("Google Chat app removed from a space; conversation memory cleared.")
        return {}

    if event_type == "MESSAGE":
        return await _handle_message(event, space_name, user_name)

    logger.info("Ignoring unsupported Google Chat event type: %s", event_type)
    return {}


@router.post("/google-chat", status_code=status.HTTP_200_OK)
async def google_chat_webhook(request: Request) -> dict[str, Any]:
    """Receive Google Chat events and return a synchronous Chat message response."""
    audience = settings.google_chat_audience
    if not audience:
        logger.error("GOOGLE_CHAT_AUDIENCE is not set; rejecting Google Chat request.")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Google Chat integration is not configured.",
        )

    if not verify_google_chat_token(request.headers.get("authorization"), audience):
        logger.warning("Rejected Google Chat request with missing or invalid bearer token.")
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing Google Chat bearer token.",
        )

    try:
        event = await request.json()
    except ValueError:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Request body must be a valid JSON object.",
        )
    if not isinstance(event, dict):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Request body must be a valid JSON object.",
        )

    return await handle_chat_event(event)
